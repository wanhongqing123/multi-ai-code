#pragma once

#include <string>

// 路径边界：把用户（其实是模型）给的路径解析成绝对路径，并确认它在 root 之内。
//
// 默认宿主的工作目录边界。模型会试着越界——有时是它自己想看 ../.env，
// 有时是被提示词注入诱导的。MaiToolContext 可由宿主指定更宽的 App 容器，
// 或在桌面端交给操作系统文件权限；默认仍走这里。
//
// 单独成一个文件是为了能被单独测：混在各个工具里就没法保证每个都做对，
// 也没法集中测 `..`、符号链接、同前缀同级目录这几种绕过手法。
//
// 别自己拼路径判断。"消掉 .. 之后比字符串前缀"这种直觉写法有两个洞：
//   符号链接      root 里的一个链接可以指到外面去
//   同前缀兄弟    /work 和 /workspace，前缀比会把后者当成前者的子目录
// 两个都有用例守着。
//
// 失败返回空字符串。**空就是不许访问**，不要退回到"那就用原路径吧"。
std::string maiResolvePathWithinRoot(const std::string& root, const std::string& candidate);
